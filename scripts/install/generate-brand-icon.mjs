/**
 * Build SuperLiora Windows .ico + PNG from the Neon Noir mark, then emit
 * scripts/install/brand-icon.mjs (base64 payload so the one-liner ships it).
 *
 * Run: node scripts/install/generate-brand-icon.mjs
 */
import { createRequire } from 'node:module';
import { Buffer } from 'node:buffer';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = import.meta.dirname;
const repoRoot = join(here, '..', '..');
const require = createRequire(join(repoRoot, 'package.json'));
const sharp = require(join(repoRoot, 'node_modules/.pnpm/sharp@0.34.5/node_modules/sharp'));

const SIZES = [16, 24, 32, 48, 64, 128, 256];

/** Full mark — Neon Noir command node (matches apps/site/public/favicon.svg). */
export function renderBrandMarkSvg(size) {
  const s = Number(size);
  const stroke = s <= 16 ? 4.8 : s <= 24 ? 4.0 : s <= 32 ? 3.4 : s <= 48 ? 2.8 : 2.4;
  const node = s <= 16 ? 5.6 : s <= 24 ? 5.0 : s <= 32 ? 4.2 : 3.4;
  const halo = node + (s <= 32 ? 2.2 : 3.4);
  const border = s <= 32 ? 2.2 : 1.6;
  return `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="${s}" height="${s}" viewBox="0 0 64 64" fill="none">
  <rect width="64" height="64" rx="16" fill="#0D1422"/>
  <rect x="2" y="2" width="60" height="60" rx="14" stroke="#00D5FF" stroke-opacity="${s <= 32 ? 0.7 : 0.42}" stroke-width="${border}"/>
  <path d="M16 42c5.2-12.4 11-19.2 16-21.2 5 2 10.8 8.8 16 21.2" stroke="#00D5FF" stroke-width="${stroke}" stroke-linecap="round"/>
  <circle cx="32" cy="20.2" r="${halo}" fill="#A78BFA" fill-opacity="0.22"/>
  <circle cx="32" cy="20.2" r="${node}" fill="#A78BFA"/>
  <path d="M20 48.5h24" stroke="#E6EDF3" stroke-opacity="0.55" stroke-width="${s <= 24 ? 2.4 : 1.8}" stroke-linecap="round"/>
</svg>
`;
}

function packIco(pngBySize) {
  const entries = [...pngBySize.entries()].toSorted((a, b) => a[0] - b[0]);
  const count = entries.length;
  const headerSize = 6 + 16 * count;
  let offset = headerSize;
  const dir = Buffer.alloc(headerSize);
  dir.writeUInt16LE(0, 0);
  dir.writeUInt16LE(1, 2);
  dir.writeUInt16LE(count, 4);
  const chunks = [dir];
  entries.forEach(([size, png], i) => {
    const entry = 6 + i * 16;
    dir.writeUInt8(size >= 256 ? 0 : size, entry);
    dir.writeUInt8(size >= 256 ? 0 : size, entry + 1);
    dir.writeUInt8(0, entry + 2);
    dir.writeUInt8(0, entry + 3);
    dir.writeUInt16LE(1, entry + 4);
    dir.writeUInt16LE(32, entry + 6);
    dir.writeUInt32LE(png.length, entry + 8);
    dir.writeUInt32LE(offset, entry + 12);
    chunks.push(png);
    offset += png.length;
  });
  return Buffer.concat(chunks);
}

async function rasterize(size) {
  const svg = renderBrandMarkSvg(size);
  return sharp(Buffer.from(svg)).resize(size, size).png().toBuffer();
}

function renderBrandIconModule(icoB64, png256B64) {
  return `/**
 * SuperLiora Neon Noir mark for desktop / Start Menu shortcuts.
 * Generated by scripts/install/generate-brand-icon.mjs — do not hand-edit the payload.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';

import { hostJoin } from './host-path.mjs';
import { defaultBinDir } from './platform.mjs';

export const BRAND_ICON_FILE = 'superliora.ico';
export const BRAND_ICON_PNG_FILE = 'superliora.png';

const ICO_B64 = '${icoB64}';
const PNG256_B64 = '${png256B64}';

export function brandIconPath(options = {}) {
  const platform = options.platform ?? process.platform;
  const binDir = options.binDir || defaultBinDir(platform);
  return hostJoin(platform, binDir, BRAND_ICON_FILE);
}

export function brandPngPath(options = {}) {
  const platform = options.platform ?? process.platform;
  const binDir = options.binDir || defaultBinDir(platform);
  return hostJoin(platform, binDir, BRAND_ICON_PNG_FILE);
}

export async function ensureBrandIcon(options = {}) {
  const dest = options.iconPath ?? brandIconPath(options);
  const pngDest = options.pngPath ?? brandPngPath(options);
  const write = options.writeFile ?? defaultWriteBinary;
  if (options.writeIco !== false) {
    await write(dest, Buffer.from(ICO_B64, 'base64'));
  }
  if (options.writePng !== false) {
    await write(pngDest, Buffer.from(PNG256_B64, 'base64'));
  }
  return dest;
}

/** Write the platform mark (Windows .ico, POSIX PNG) and return its path. */
export async function materializeBrandShortcutIcon(options = {}) {
  const platform = options.platform ?? process.platform;
  try {
    if (platform === 'win32') {
      return await ensureBrandIcon({
        platform,
        binDir: options.binDir,
        iconPath: options.iconPath,
        writePng: options.writePng === true,
        writeFile: options.writeFile,
      });
    }
    const pngDest = options.pngPath ?? brandPngPath({ platform, binDir: options.binDir });
    await ensureBrandIcon({
      platform,
      binDir: options.binDir,
      pngPath: pngDest,
      writeIco: false,
      writeFile: options.writeFile,
    });
    return pngDest;
  } catch {
    return undefined;
  }
}

async function defaultWriteBinary(dest, bytes) {
  await mkdir(dirname(dest), { recursive: true });
  await writeFile(dest, bytes);
}
`;
}

async function main() {
  const pngBySize = new Map();
  for (const size of SIZES) {
    pngBySize.set(size, await rasterize(size));
  }
  const ico = packIco(pngBySize);
  const png256 = pngBySize.get(256);
  const outDir = here;
  await mkdir(outDir, { recursive: true });
  await writeFile(join(outDir, 'superliora.ico'), ico);
  await writeFile(join(outDir, 'superliora.png'), png256);
  await writeFile(
    join(outDir, 'brand-icon.mjs'),
    renderBrandIconModule(ico.toString('base64'), png256.toString('base64')),
    'utf8',
  );
  process.stdout.write(`wrote ico ${ico.length} bytes, png ${png256.length} bytes\n`);
}

await main();
