#!/usr/bin/env node
/**
 * Refreshes the landing page's provider-catalog facts from the same source the
 * TUI reads: `https://models.dev/api.json`.
 *
 * `/login` lists whatever models.dev publishes at the moment the user opens
 * the dialog, so the landing page must not hard-code a provider list. The
 * generated module keeps the marketing copy honest between deploys, and the
 * Pages workflow re-runs this script on every publish.
 *
 *   node ./scripts/sync-provider-catalog.mjs [--out <path>] [--check]
 *
 * Env:
 *   MODELS_DEV_URL  catalog URL (default https://models.dev/api.json)
 *   MODELS_DEV_FILE  read a local api.json instead of fetching (offline runs)
 *
 * A failed fetch leaves the committed snapshot untouched and exits 0, so a
 * model of an outage never blocks a deploy. Pass --strict to fail instead.
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const scriptDir = import.meta.dirname;
const outFile = argValue('--out') ?? resolve(scriptDir, '../src/data/provider-catalog.generated.ts');
const checkOnly = process.argv.includes('--check');
const strict = process.argv.includes('--strict');
const MAX_CHIPS = 28;

// Rows the TUI pins to the top of the /login picker come first in the marquee,
// then the biggest catalogs, so the strip reads as "the usual suspects, plus a
// very long tail" instead of an arbitrary alphabetical slice.
const FEATURED = [
  'anthropic',
  'openai',
  'google',
  'xai',
  'openrouter',
  'deepseek',
  'groq',
  'mistral',
  'togetherai',
  'cerebras',
  'perplexity',
  'azure',
  'amazon-bedrock',
  'alibaba',
];

function argValue(flag) {
  const i = process.argv.indexOf(flag);
  return i === -1 ? undefined : process.argv[i + 1];
}

async function loadCatalog() {
  const file = process.env['MODELS_DEV_FILE'];
  if (file !== undefined && file.length > 0) return JSON.parse(readFileSync(resolve(file), 'utf8'));
  const url = process.env['MODELS_DEV_URL'] || 'https://models.dev/api.json';
  const res = await fetch(url, { headers: { Accept: 'application/json' }, signal: AbortSignal.timeout(30_000) });
  if (!res.ok) throw new Error(`${url} → HTTP ${String(res.status)}`);
  const raw = await res.json();
  if (typeof raw !== 'object' || raw === null || Array.isArray(raw)) {
    throw new Error(`${url} returned an unexpected payload shape`);
  }
  return raw;
}

function toRows(raw) {
  return Object.entries(raw)
    .map(([id, entry]) => {
      const models = entry !== null && typeof entry === 'object' ? entry.models : undefined;
      const count = models !== null && typeof models === 'object' ? Object.keys(models).length : 0;
      const name = typeof entry?.name === 'string' && entry.name.length > 0 ? entry.name : id;
      return { id, name, models: count };
    })
    .filter((row) => row.models > 0);
}

function orderRows(rows) {
  const rank = new Map(FEATURED.map((id, i) => [id, i]));
  return rows.toSorted((a, b) => {
    const ra = rank.get(a.id) ?? Number.MAX_SAFE_INTEGER;
    const rb = rank.get(b.id) ?? Number.MAX_SAFE_INTEGER;
    if (ra !== rb) return ra - rb;
    if (b.models !== a.models) return b.models - a.models;
    return a.name.localeCompare(b.name);
  });
}

function render(rows) {
  const providerCount = rows.length;
  const modelCount = rows.reduce((sum, row) => sum + row.models, 0);
  const chips = rows.slice(0, MAX_CHIPS).map((row) => `    { name: ${JSON.stringify(row.name)}, models: ${String(row.models)} },`);
  return `/* Generated by scripts/sync-provider-catalog.mjs — do not edit by hand. */
/* Facts come from https://models.dev/api.json — the catalog /login reads. */
/* Refresh with \`pnpm -C apps/site run catalog:sync\`; the Pages workflow runs it per deploy. */

export interface CatalogProviderChip {
  readonly name: string;
  readonly models: number;
}

export interface ProviderCatalogSnapshot {
  /** Where the numbers come from, shown next to the strip so the claim is checkable. */
  readonly source: string;
  /** UTC date of the snapshot the counts below were taken from. */
  readonly snapshotDate: string;
  readonly providerCount: number;
  readonly modelCount: number;
  /** Largest / most-used catalogs first; the marquee renders these, then "+N more". */
  readonly providers: readonly CatalogProviderChip[];
}

export const PROVIDER_CATALOG: ProviderCatalogSnapshot = {
  source: "models.dev",
  snapshotDate: ${JSON.stringify(new Date().toISOString().slice(0, 10))},
  providerCount: ${String(providerCount)},
  modelCount: ${String(modelCount)},
  providers: [
${chips.join('\n')}
  ],
};
`;
}

try {
  const rows = orderRows(toRows(await loadCatalog()));
  if (rows.length < 10) throw new Error(`catalog looks truncated (${String(rows.length)} providers) — refusing to write`);
  const next = render(rows);
  const current = (() => {
    try {
      return readFileSync(outFile, 'utf8');
    } catch {
      return '';
    }
  })();
  if (checkOnly) {
    if (current !== next) {
      console.error(`sync-provider-catalog: ${outFile} is stale — run \`pnpm -C apps/site run catalog:sync\``);
      process.exit(1);
    }
    console.log('sync-provider-catalog: up to date');
    process.exit(0);
  }
  if (current === next) {
    console.log(`sync-provider-catalog: unchanged (${String(rows.length)} providers)`);
    process.exit(0);
  }
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, next, 'utf8');
  console.log(
    `sync-provider-catalog: wrote ${String(rows.length)} providers / ` +
      `${String(rows.reduce((s, r) => s + r.models, 0))} model rows`,
  );
} catch (error) {
  const message = error instanceof Error ? error.message : String(error);
  if (strict) {
    console.error(`sync-provider-catalog: FAIL — ${message}`);
    process.exit(1);
  }
  console.warn(`sync-provider-catalog: skipped (${message}); keeping the committed snapshot`);
}
